import healthRoutes from './routes/Health.routes.js';
import { errorHandler } from './middleware/error.middleware.js';

const app = express();
app.use(cors({ origin: env.frontendOrigin }));
app.use(express.json({ limit: '1mb' }));
app.use('/api', healthRoutes);
app.use('/api/auth', authRoutes);
app.use('/api/clients', clientsRoutes);
app.use('/api/products', productsRoutes);
app.use('/api/trials', descargasPruebaRoutes);
app.use('/api/campanas_marketing', campanasMarketingRoutes);
app.use('/api/marketing', accionesMarketingRoutes);
app.use('/api/activities', actividadWebRoutes);
app.use('/api/dashboard', dashboardRoutes);
app.use('/api/assignments', asignacionesCrmRoutes);
app.use('/api/interactions', interactionsRoutes);
app.use('/api/sales', salesRoutes);
app.use('/api/reports', reportsRoutes);
app.use('/api/empresas', companiesRoutes);
app.use('/api/users', usersRoutes);
app.use('/api/vendors', vendorsRoutes);
