import express from 'express';
import cors from 'cors';
import { env } from '../config/env.js';
import authRoutes from './routes/Auth.routes.js';
import clientsRoutes from './routes/Clientes.routes.js';
import productsRoutes from './routes/Productos.routes.js';
import descargasPruebaRoutes from './routes/DescargasPrueba.routes.js';
import campanasMarketingRoutes from './routes/CampanasMarketing.routes.js';
import accionesMarketingRoutes from './routes/AccionesMarketing.routes.js';
import actividadWebRoutes from './routes/ActividadWeb.routes.js';
import dashboardRoutes from './routes/Dashboard.routes.js';
import asignacionesCrmRoutes from './routes/AsignacionesCrm.routes.js';
import interactionsRoutes from './routes/Interacciones.routes.js';
import salesRoutes from './routes/Ventas.routes.js';
import reportsRoutes from './routes/Reportes.routes.js';
import companiesRoutes from './routes/Empresas.routes.js';
import usersRoutes from './routes/Usuarios.routes.js';
